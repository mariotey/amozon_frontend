from django.db import models

class User(models.Model):
    user_id = models.CharField(max_length=255, primary_key=True)
    num_reviews = models.IntegerField(null=True)
    avg_rating_given = models.FloatField(null=True)
    rating_std = models.FloatField(null=True)
    min_rating_given = models.FloatField(null=True)
    max_rating_given = models.FloatField(null=True)
    first_review_date = models.DateTimeField(null=True)
    last_review_date = models.DateTimeField(null=True)
    total_recency_weight = models.FloatField(null=True)
    total_helpful_votes_received = models.FloatField(null=True)
    avg_helpful_votes_per_review = models.FloatField(null=True)
    num_verified_purchases = models.FloatField(null=True)
    avg_review_length = models.FloatField(null=True)
    avg_review_words = models.FloatField(null=True)
    num_review_img_sum = models.FloatField(null=True)
    extreme_rating_ratio = models.FloatField(null=True)
    positive_rating_ratio = models.FloatField(null=True)
    negative_rating_ratio = models.FloatField(null=True)
    avg_price_purchased = models.FloatField(null=True)
    free_app_ratio = models.FloatField(null=True)
    days_active = models.IntegerField(null=True)
    reviews_per_day = models.FloatField(null=True)
    verified_purchase_ratio = models.FloatField(null=True)
    user_segment = models.CharField(max_length=50, null=True)
    is_discriminating = models.BooleanField(null=True)

    class Meta:
        db_table = "Users"


class Item(models.Model):
    parent_asin = models.CharField(max_length=255, primary_key=True)
    num_reviews = models.IntegerField(null=True)
    avg_rating = models.FloatField(null=True)
    rating_std = models.FloatField(null=True)
    min_rating = models.FloatField(null=True)
    max_rating = models.FloatField(null=True)
    first_review_date = models.DateTimeField(null=True)
    last_review_date = models.DateTimeField(null=True)
    total_recency_weight = models.FloatField(null=True)
    total_helpful_votes = models.FloatField(null=True)
    avg_helpful_votes = models.FloatField(null=True)
    num_verified_reviews = models.FloatField(null=True)
    positive_review_ratio = models.FloatField(null=True)
    negative_review_ratio = models.FloatField(null=True)
    item_title = models.TextField(null=True)
    main_category = models.CharField(max_length=255, null=True)
    categories = models.TextField(null=True)
    description = models.TextField(null=True)
    features = models.TextField(null=True)
    details = models.TextField(null=True)
    store = models.CharField(max_length=255, null=True)
    price = models.FloatField(null=True)
    item_images = models.TextField(null=True)
    item_videos = models.TextField(null=True)
    num_item_img = models.IntegerField(null=True)
    num_item_videos = models.IntegerField(null=True)
    num_categories = models.IntegerField(null=True)
    is_free = models.BooleanField(null=True)
    has_price_info = models.BooleanField(null=True)
    price_bucket = models.CharField(max_length=50, null=True)
    days_on_platform = models.IntegerField(null=True)
    reviews_per_day = models.FloatField(null=True)
    verified_review_ratio = models.FloatField(null=True)
    popularity_segment = models.CharField(max_length=50, null=True)
    quality_score = models.FloatField(null=True)

    class Meta:
        db_table = "Items"


class Review(models.Model):
    review_id = models.CharField(max_length=255, primary_key=True)
    asin = models.CharField(max_length=255, null=True)
    parent_asin = models.CharField(max_length=255, null=True)
    user_id = models.CharField(max_length=255, null=True)
    review_title = models.TextField(null=True)
    review_text = models.TextField(null=True)
    review_datetime = models.DateTimeField(null=True)
    review_year = models.IntegerField(null=True)
    review_month = models.IntegerField(null=True)
    review_rating = models.FloatField(null=True)
    verified_purchase = models.BooleanField(null=True)
    helpful_vote = models.IntegerField(null=True)
    review_images = models.TextField(null=True)
    review_text_length = models.IntegerField(null=True)
    review_title_length = models.IntegerField(null=True)
    review_word_count = models.IntegerField(null=True)
    is_extreme_rating = models.BooleanField(null=True)
    is_positive = models.BooleanField(null=True)
    is_negative = models.BooleanField(null=True)
    num_review_img = models.IntegerField(null=True)
    days_since_review = models.IntegerField(null=True)
    recency_weight = models.FloatField(null=True)

    class Meta:
        db_table = "Reviews"
